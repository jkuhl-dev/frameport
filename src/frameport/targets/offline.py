LAUNCH_SH_TEMPLATE = r"""#!/usr/bin/env bash
# Steam Frame launcher for {title} ({package}). Generated by FramePort.
set -euo pipefail

app_dir="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
[[ -d "$app_dir/lepton-app" ]] || {{ echo "Game files missing at $app_dir (storage not mounted?)" >&2; exit 1; }}

exec 9>"$app_dir/.launch.lock"
flock -n 9 || {{
    echo "$(date +%s) already starting or running: second launch ignored" >>"$app_dir/launch-dup.log"
    exit 0
}}

fix_perms() {{
    find "$app_dir/lepton-data/external" -type d \( ! -perm -u+rwx -o ! -perm -g+rwx \) \
        -exec chmod u+rwx,g+rwx {{}} + 2>/dev/null || true
}}

mkdir -p "$app_dir/lepton-data/external/Android/data/{package}/files" \
         "$app_dir/lepton-data/external/Android/data/{package}/cache" \
         "$app_dir/lepton-data/external/Android/data/{package}/files/cloud/data" 2>/dev/null || true

fix_perms
parent=$PPID
(
    while sleep 2 && kill -0 $$ 2>/dev/null; do
        fix_perms
        if [[ $parent -gt 1 ]] && ! kill -0 $parent 2>/dev/null; then
            kill -TERM $$
        fi
    done
) 9>&- &
permfix=$!

export SteamAppId={appid}
export STEAM_COMPAT_INSTALL_PATH="$app_dir/lepton-app"
export STEAM_COMPAT_DATA_PATH="$app_dir/lepton-data"
export STEAM_COMPAT_SHADER_PATH="$app_dir/lepton-shaders"
export STEAM_COMPAT_LIBRARY_PATHS="$app_dir"
export LEPTON_ENV_FRAMEBRIDGE_CONFIG="$app_dir/settings.conf"
export XDG_RUNTIME_DIR="/run/user/$(id -u)"
export DBUS_SESSION_BUS_ADDRESS="unix:path=$XDG_RUNTIME_DIR/bus"
export IS_PARENT=true
{extra_env}
child=''
stop() {{
    trap - EXIT INT TERM
    kill $permfix 2>/dev/null || true
    [[ -n "$child" ]] && kill -TERM -- "-$child" 2>/dev/null || true
    podman kill "lepton-steamlaunch-$SteamAppId" >/dev/null 2>&1 || true
}}
trap stop EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

LEPTON_BIN="$HOME/.local/share/Steam/steamapps/common/Lepton/lepton"
if [[ ! -x "$LEPTON_BIN" ]]; then
    if command -v lepton >/dev/null 2>&1; then
        LEPTON_BIN="$(command -v lepton)"
    else
        echo "Lepton not found at $LEPTON_BIN. Ensure Lepton is installed via Steam." >&2
        exit 1
    fi
fi

setsid "$LEPTON_BIN" start >"$app_dir/launch.log" 2>&1 &
child=$!
rc=0; wait "$child" || rc=$?
exit $rc
"""


class OfflineTarget(Target):
    kind = "offline"
    label = "Offline Folder"

    def __init__(self, outdir: Path | None = None, move: bool = False, fetch_art: bool = True):
        self.outdir = (outdir or Path.cwd()).resolve()
        self.move = move
        self.fetch_art = fetch_art

    def describe(self) -> dict:
        return {"kind": "offline", "outdir": str(self.outdir)}

    def installed(self) -> list[dict]:
        return []

    def install(
        self,
        package: str,
        title: str,
        apk: Path,
        data_dir: Path | None,
        recipe: Recipe,
        reporter: Reporter,
        apk_only: bool = False,
        data_files: list[str] | None = None,
    ) -> dict:
        reporter.stage("Generate offline game directory")
        target_dir = self.outdir / package
        app_dir = target_dir / "lepton-app"
        obb_dir = app_dir / "obb"
        data_target_dir = target_dir / "lepton-data"
        shaders_dir = target_dir / "lepton-shaders"
        art_target_dir = target_dir / "artwork"

        app_dir.mkdir(parents=True, exist_ok=True)
        obb_dir.mkdir(parents=True, exist_ok=True)
        data_target_dir.mkdir(parents=True, exist_ok=True)
        shaders_dir.mkdir(parents=True, exist_ok=True)
        art_target_dir.mkdir(parents=True, exist_ok=True)

        # 1. Place APK
        dest_apk = app_dir / "game.apk"
        if self.move:
            shutil.move(apk, dest_apk)
        else:
            shutil.copy2(apk, dest_apk)
        reporter.log(f"APK -> {dest_apk.relative_to(self.outdir)}")

        # 2. Place OBB / data files
        local_manifest: dict[str, int] = {}
        if data_dir and not apk_only:
            local = local_data_manifest(data_dir, data_files)
            names = frame_names(package, local)
            for rel, size in local.items():
                src_file = data_dir / rel
                target_name = names.get(rel, rel)
                dest_obb = obb_dir / target_name
                dest_obb.parent.mkdir(parents=True, exist_ok=True)
                if self.move:
                    shutil.move(src_file, dest_obb)
                else:
                    shutil.copy2(src_file, dest_obb)
                local_manifest[target_name] = size
                reporter.log(f"OBB ({target_name}) -> {dest_obb.relative_to(self.outdir)}")

        # 3. Context, configuration & settings
        entry = library.game(package) or {}
        ctx = install_context(recipe)
        config_args = configuration_args(entry, recipe) if entry else {}
        settings = config_args.get("settings") or ctx.adapter_settings or {}

        settings_lines = [f"{k}={v}\n" for k, v in settings.items()]
        (target_dir / "settings.conf").write_text("".join(settings_lines), encoding="utf-8")

        files_dir = data_target_dir / "external" / "Android" / "data" / package / "files"
        files_dir.mkdir(parents=True, exist_ok=True)
        (files_dir / "framebridge.conf").write_text("".join(settings_lines), encoding="utf-8")
        (data_target_dir / "external" / "Android" / "data" / package / "cache").mkdir(parents=True, exist_ok=True)
        (files_dir / "cloud" / "data").mkdir(parents=True, exist_ok=True)

        # Managed config files from patches
        for rel, content in (ctx.files or {}).items():
            f_dest = files_dir / rel
            f_dest.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                f_dest.write_bytes(content)
            else:
                f_dest.write_text(str(content), encoding="utf-8")

        # Flatscreen marker if 2D app
        if show_window(ctx, _flatscreen(package)):
            (app_dir / "lepton-show-flatscreen").touch()

        # 4. Artwork
        if self.fetch_art:
            reporter.stage("Artwork for Steam library")
            try:
                artwork_fetch.fetch(package, dest_apk if dest_apk.is_file() else apk)
                art_set = steam_set_for(package)
                for kind, art_path in (art_set or {}).items():
                    if art_path and Path(art_path).is_file():
                        p = Path(art_path)
                        shutil.copy2(p, art_target_dir / f"{kind}{p.suffix}")
            except Exception as exc:  # noqa: BLE001
                reporter.log(f"Artwork fetch skipped: {exc}")

        # 5. AppID & deployment.json
        anchor_exe = f'"/home/deck/Applications/quest-frame/{package}/launch.sh"'
        appid = zlib.crc32((anchor_exe + title).encode("utf-8")) | 0x80000000

        apk_st = dest_apk.stat()
        dep = {
            "package": package,
            "title": title,
            "appid": int(appid),
            "base": f"/home/deck/Applications/quest-frame/{package}",
            "anchor": f"/home/deck/Applications/quest-frame/{package}",
            "kind": "quest",
            "apk": "game.apk",
            "sha256": sha256(dest_apk),
            "apk_size": apk_st.st_size,
            "apk_stat": {"size": apk_st.st_size, "mtime_ns": apk_st.st_mtime_ns},
            "recipe": deployment_recipe(recipe),
            "installed_by": "frameport-offline",
            "time": time.time(),
            "settings": settings,
        }
        if local_manifest:
            dep["data_manifest"] = local_manifest
        (target_dir / "deployment.json").write_text(json.dumps(dep, indent=2), encoding="utf-8")

        # 6. launch.sh
        env_lines = [f'export {k}="{v}"' for k, v in (ctx.env or {}).items()]
        extra_env_str = "\n".join(env_lines) + ("\n" if env_lines else "")
        launch_content = LAUNCH_SH_TEMPLATE.format(
            title=title,
            package=package,
            appid=int(appid),
            extra_env=extra_env_str,
        )
        launch_file = target_dir / "launch.sh"
        launch_file.write_text(launch_content, encoding="utf-8")
        launch_file.chmod(0o755)

        return {
            "ok": True,
            "path": str(target_dir),
            "package": package,
            "title": title,
            "appid": int(appid),
            "base": str(target_dir),
        }

    def add_to_library(self, packages: list[str], reporter: Reporter) -> dict:
        return {"ok": True, "packages": packages}

    def launch_test(self, package: str, reporter: Reporter, seconds: int = 45):
        raise NotImplementedError("Offline target does not support running live tests")

    def set_settings(self, package: str, settings: dict, *, foveation=None) -> dict:
        target_dir = self.outdir / package
        conf = target_dir / "settings.conf"
        if conf.exists():
            existing = {}
            for line in conf.read_text(encoding="utf-8").splitlines():
                if "=" in line:
                    k, v = line.split("=", 1)
                    existing[k.strip()] = v.strip()
            existing.update({k: str(v) for k, v in settings.items()})
            conf.write_text("".join(f"{k}={v}\n" for k, v in existing.items()), encoding="utf-8")
        return {"ok": True}

    def uninstall(self, package: str, keep_data: bool = True) -> dict:
        target_dir = self.outdir / package
        if target_dir.exists():
            shutil.rmtree(target_dir, ignore_errors=True)
        return {"ok": True}
